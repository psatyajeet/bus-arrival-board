def draw_small(bitmap, text, gap=1):
    bitmap.fill(0)
    cursor = 0
    for character in text:
        rows = SMALL_GLYPHS.get(character, SMALL_GLYPHS["-"])
        width = len(rows[0])
        if cursor + width > bitmap.width:
            break
        for y, row in enumerate(rows):
            for x, pixel in enumerate(row):
                if pixel == "1":
                    bitmap[cursor + x, y] = 1
        cursor += width + gap
